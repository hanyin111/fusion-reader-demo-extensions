  items(books) { return books.map(book => ({
    title: book.title, url: `demo:${book.id}`,
    cover: `https://hanyin111.github.io/fusion-reader-demo-extensions/covers/${book.id}.png`,
    update: `${book.chapters.length}章 · 原创演示`,
  })); }
  async latest(page) { return Number(page) === 1 ? this.items(this.books()) : []; }
  async search(keyword, page) {
    return Number(page) === 1 ? this.items(this.books().filter(book =>
      `${book.title} ${book.author} ${book.desc}`.includes(keyword))) : [];
  }
  async searchAuthor(author, page) { return this.search(author.name, page); }
  async detail(url) {
    const book = this.books().find(book => url === `demo:${book.id}`);
    if (!book) throw new Error('演示作品不存在');
    return { ...this.items([book])[0], desc: book.desc, authors: [{ name: book.author }],
      episodes: [{ title: '原创正文', urls: book.chapters.map((chapter, i) =>
        ({ name: chapter.title, url: `demo:${book.id}/${i}` })) }],
    };
  }
  async watch(url) {
    const match = /^demo:([a-z]+)\/(\d+)$/.exec(url);
    const book = match && this.books().find(book => book.id === match[1]);
    const chapter = book && book.chapters[Number(match[2])];
    if (!chapter) throw new Error('演示章节不存在');
    return { content: chapter.content };
  }
